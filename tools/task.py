#!/usr/bin/env python3
"""Record task start/finish times and regenerate TASKS.md.

tasks/tasks.csv is the source of truth. Every start/done updates it and rewrites
TASKS.md, so committing after each step leaves a timestamped trail in git.

Usage:
    python3 tools/task.py list
    python3 tools/task.py start S1.1
    python3 tools/task.py done  S1.1 --hours 9 --note "theory notes in stage-1-mlkem/notes.md"
    python3 tools/task.py report
"""

import argparse
import csv
import sys
from datetime import date, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "tasks" / "tasks.csv"
BOARD_PATH = ROOT / "TASKS.md"
FIELDS = ["id", "stage", "title", "due", "started", "finished", "hours", "note"]

STAGES = {
    "1": ("Stage 1 · The theory", "stage-1-mlkem/"),
    "2": ("Stage 2 · The NTT on a GPU", "stage-2-ntt-gpu/"),
    "3": ("Stage 3 · Side channels on GPUs", "stage-3-gpu-side-channels/"),
}


def load():
    with CSV_PATH.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def save(rows):
    with CSV_PATH.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(rows)


def now_stamp():
    # Local time with UTC offset, minute precision, e.g. 2026-10-18T09:30+03:00
    return datetime.now().astimezone().isoformat(timespec="minutes")


def parse_stamp(value):
    return datetime.fromisoformat(value) if value else None


def find(rows, task_id):
    for row in rows:
        if row["id"].lower() == task_id.lower():
            return row
    sys.exit(f"Unknown task: {task_id}. Run 'python3 tools/task.py list' to see the IDs.")


def elapsed(row):
    start, end = parse_stamp(row["started"]), parse_stamp(row["finished"])
    if not (start and end):
        return ""
    minutes = int((end - start).total_seconds() // 60)
    days, rest = divmod(minutes, 24 * 60)
    hours, mins = divmod(rest, 60)
    if days:
        return f"{days}d {hours}h"
    return f"{hours}h {mins:02d}m"


def status(row, today):
    due = date.fromisoformat(row["due"])
    if row["finished"]:
        finished = parse_stamp(row["finished"]).date()
        late = (finished - due).days
        return "✅ Done" if late <= 0 else f"✅ Done ({late}d late)"
    if due < today:
        prefix = "🔴 Overdue, in progress" if row["started"] else "🔴 Overdue"
        return f"{prefix} ({(today - due).days}d)"
    if row["started"]:
        return "⏳ In progress"
    return "⬜ Not started"


def short(stamp):
    return parse_stamp(stamp).strftime("%d %b %H:%M") if stamp else ""


def render(rows, today):
    done = [r for r in rows if r["finished"]]
    overdue = [r for r in rows if not r["finished"] and date.fromisoformat(r["due"]) < today]
    hours = sum(float(r["hours"]) for r in rows if r["hours"])

    lines = [
        "# Task Board",
        "",
        "[← back to overview](README.md) · Generated by `tools/task.py` from "
        "[`tasks/tasks.csv`](tasks/tasks.csv). Do not edit by hand.",
        "",
        f"**Status as of {today.isoformat()}:** {len(done)}/{len(rows)} done · "
        f"{len(overdue)} overdue · {hours:g} hands-on hours logged",
        "",
        "*Started/Finished are recorded when the task is opened and closed. Elapsed is calendar "
        "time between them; Hours is hands-on time I log at the end.*",
    ]
    for stage, (title, folder) in STAGES.items():
        lines += [
            "",
            f"## [{title}]({folder})",
            "",
            "| ID | Task | Due | Started | Finished | Elapsed | Hours | Status |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for r in (r for r in rows if r["stage"] == stage):
            due = date.fromisoformat(r["due"]).strftime("%d %b")
            title_cell = r["title"] + (f"<br><sub>{r['note']}</sub>" if r["note"] else "")
            lines.append(
                f"| {r['id']} | {title_cell} | {due} | {short(r['started'])} | "
                f"{short(r['finished'])} | {elapsed(r)} | {r['hours']} | {status(r, today)} |"
            )
    BOARD_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def cmd_list(rows, today):
    for r in rows:
        print(f"{r['id']:<5} {r['due']}  {status(r, today):<28} {r['title']}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("list", help="show all tasks")
    sub.add_parser("report", help="regenerate TASKS.md")
    start = sub.add_parser("start", help="stamp the start time of a task")
    start.add_argument("id")
    done = sub.add_parser("done", help="stamp the finish time of a task")
    done.add_argument("id")
    done.add_argument("--hours", type=float, help="hands-on hours spent")
    done.add_argument("--note", help="short note, e.g. where the result lives")
    args = parser.parse_args()

    rows = load()
    today = date.today()

    if args.command == "list":
        cmd_list(rows, today)
        return

    if args.command == "start":
        row = find(rows, args.id)
        if row["started"]:
            sys.exit(f"{row['id']} was already started at {row['started']}.")
        row["started"] = now_stamp()
        print(f"Started {row['id']} at {row['started']}")

    if args.command == "done":
        row = find(rows, args.id)
        if row["finished"]:
            sys.exit(f"{row['id']} was already finished at {row['finished']}.")
        if not row["started"]:
            sys.exit(f"{row['id']} was never started. Run 'start {row['id']}' first.")
        row["finished"] = now_stamp()
        if args.hours is not None:
            row["hours"] = f"{args.hours:g}"
        if args.note:
            row["note"] = args.note
        print(f"Finished {row['id']} at {row['finished']} (elapsed {elapsed(row)})")

    save(rows)
    render(rows, today)
    print(f"Updated {BOARD_PATH.relative_to(ROOT)}. Commit it to record the timestamp.")


if __name__ == "__main__":
    main()
